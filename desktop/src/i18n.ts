export type Copy = typeof zh;
export type Lang = "zh" | "zh-Hant" | "en";

export function parseLang(value: unknown): Lang | null {
  const raw = String(value || "").trim();
  if (!raw) return null;
  const lower = raw.toLowerCase().replace(/_/g, "-");
  if (lower === "zh-hant" || lower.startsWith("zh-hant") || lower.startsWith("zh-tw") || lower.startsWith("zh-hk") || lower.startsWith("zh-mo")) {
    return "zh-Hant";
  }
  if (lower === "en" || lower.startsWith("en-")) return "en";
  if (lower === "zh" || lower.startsWith("zh-hans") || lower.startsWith("zh-cn") || lower.startsWith("zh-sg") || lower.startsWith("zh")) {
    return "zh";
  }
  return null;
}

export function detectLang(): Lang {
  if (typeof navigator === "undefined") return "zh";
  for (const item of [navigator.language, ...(navigator.languages || [])]) {
    const parsed = parseLang(item);
    if (parsed) return parsed;
  }
  return "zh";
}

export function htmlLang(lang: Lang) {
  if (lang === "en") return "en";
  if (lang === "zh-Hant") return "zh-Hant";
  return "zh-CN";
}

export function fill(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function t(lang: Lang): Copy {
  if (lang === "en") return en;
  if (lang === "zh-Hant") return zhHant;
  return zh;
}
